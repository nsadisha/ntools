'use strict';

const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');

const REQUIRED_KEYS = [
  'APPWRITE_API_ENDPOINT',
  'APPWRITE_PROJECT_ID',
  'APPWRITE_DB_ID',
  'MESSAGES_COLLECTION_ID',
  'BUGS_COLLECTION_ID',
  'NEW_TOOL_REQUESTS_COLLECTION_ID',
];

const OUTPUT_PATH = path.join(__dirname, '..', 'src', 'environment', 'environment.ts');

function buildEnvironmentFileContent(env, keys) {
  const missing = keys.filter((key) => !env[key]);

  if (missing.length > 0) {
    console.warn(
      `[generate-environment] Missing .env value(s): ${missing.join(', ')}. ` +
        'Copy .env.example to .env and fill them in. Continuing with empty strings for now.'
    );
  }

  const entries = keys.map((key) => `  ${key}: ${JSON.stringify(env[key] || '')}`).join(',\n');

  return (
    '// This file is generated by scripts/generate-environment.js from .env — do not edit directly.\n' +
    'export const environment = {\n' +
    entries +
    '\n};\n'
  );
}

function main() {
  dotenv.config();
  const content = buildEnvironmentFileContent(process.env, REQUIRED_KEYS);
  fs.writeFileSync(OUTPUT_PATH, content);
}

if (require.main === module) {
  main();
}

module.exports = { buildEnvironmentFileContent, REQUIRED_KEYS };
